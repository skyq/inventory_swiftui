  @Test("Совпадает с эталонным Snowball на словаре")
  func matchesReference() {
    let mismatches = Self.reference.compactMap { word, expected -> String? in
      let actual = RussianStemmer.stem(word)
      return actual == expected ? nil : "\(word): \(actual) != \(expected)"
    }
    #expect(mismatches.isEmpty, "\(mismatches)")
  }

  @Test("ё и е дают одну основу")
  func yoAndE() {
    #expect(RussianStemmer.stem("ёлку") == RussianStemmer.stem("елку"))
    #expect(RussianStemmer.stem("ёлка") == "елк")
  }

  @Test("Формы «куртка» дают общую основу и общий ключ уменьшительных")
  func diminutiveForms() {
    let forms = ["куртка", "куртки", "куртку", "куртке", "курточку"]
    let stems = Set(forms.map(RussianStemmer.stem))
    #expect(stems == ["куртк", "курточк"])
    let keys = Set(forms.map { RussianStemmer.diminutive(RussianStemmer.stem($0)) })
    #expect(keys == ["курт"])
  }

  @Test("Неродственное слово не получает ключ «куртка»")
  func unrelated() {
    #expect(RussianStemmer.diminutive(RussianStemmer.stem("куртина")) != "курт")
    #expect(RussianStemmer.stem("курс") != RussianStemmer.stem("куртка"))
  }

  @Test("Короткие слова и слова без гласных не падают")
  func shortWords() {
    for word in ["", "а", "к", "бцд", "нн", "ь", "и"] {
      _ = RussianStemmer.stem(word)
    }
  }

  @Test("Уменьшительный ключ не режет основу короче четырёх символов")
  func diminutiveFloor() {
    #expect(RussianStemmer.diminutive("кот") == "кот")
    #expect(RussianStemmer.diminutive("котик") == "коти")
  }
